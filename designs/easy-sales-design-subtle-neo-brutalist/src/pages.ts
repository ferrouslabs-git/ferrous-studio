// A page one wireframe shares with another (a nav item reaching another
// wireframe's page, or a link that opens a page "into" a region) gets a second
// entry under the host it is drawn in: id `<page id>@<host id>`, same
// `sourceId` and component. Links name the source id; lib/nav.tsx picks the
// entry nearest the page on show, so the host's shell stays on screen.
