export type Presentation = "modal" | "drawer" | "drawer-left";

export interface WireframeEntry {
  /** The wireframe id (`wireframeId` in the brief). */
  id: string;
  /** `wireframeName`: what the wireframe switcher shows. */
  name: string;
  /** The page this wireframe opens on: its `landingPageId`, else the first
   *  page its shell's nav links to. */
  landingPageId: string;
}

export interface PageEntry {
  /** The registry id: the wireframe page id, or `<page id>@<host id>`. */
  id: string;
  /** The wireframe page this entry draws. Links in the brief name this. */
  sourceId: string;
  /** The wireframe the page is shown in: one of WIREFRAMES. */
  wireframeId: string;
  /** Hash route, without the leading #. A placed page's path is relative to
   *  its parent's. */
  path: string;
  title: string;
  component: ComponentType;
  /** The page whose region it renders in (an <Outlet />). For an overlay,
   *  only where its address sits. */
  parentId?: string;
  /** Set when the wireframe page has a `presentation`: it opens over the
   *  page it was linked from instead of replacing it. */
  presentation?: Presentation;
}

